#!/usr/bin/env python3
"""Build the strict RoboTwin official50 x clean50 manual-goal runtime dataset.

The runtime root is deliberately lightweight: official LeRobot v3 parquet and
videos remain in the immutable source root and are exposed through symlinks.
Only compatibility metadata, the authoritative family map, manually designed
goal annotations, the goal-graph specification, and the training manifest are
created locally.
"""


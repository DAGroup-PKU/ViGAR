SPLIT_SCHEMA_VERSION = "robotwin-semantic-split/v1"
ANNOTATION_SCHEMA_VERSION = "robotwin-manual-subgoal-annotation/v2"
GOAL_GRAPH_VERSION = "official50-clean50-stage-success-v6-22s28e/v2"

